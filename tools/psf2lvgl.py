#!/usr/bin/env python3
"""Convert a Linux console PSF font (PSF1/PSF2, e.g. Terminus) into an LVGL 1-bpp C font.
Keeps the hand-drawn pixels exactly: no scaling, no anti-aliasing.
usage: psf2lvgl.py <font.psf[.gz]> <c_name> <out.c> [term]
`term` adds the box-drawing, block and shade glyphs a terminal needs (U+2500..U+259F)."""
import gzip, struct, sys

def load_psf(path):
    data = (gzip.open if path.endswith('.gz') else open)(path, 'rb').read()
    if data[:2] == b'\x36\x04':
        mode, h = data[2], data[3]
        n, w, bpg, off = (512 if mode & 1 else 256), 8, h, 4
        has_tab = bool(mode & 2)
    elif data[:4] == b'\x72\xb5\x4a\x86':
        _, off, flags, n, bpg, h, w = struct.unpack('<7I', data[4:32])
        has_tab = bool(flags & 1)
    else:
        sys.exit('not a PSF font')
    row = (w + 7) // 8
    glyphs = [data[off + i * bpg: off + (i + 1) * bpg] for i in range(n)]
    cmap = {}
    if has_tab:
        p = off + n * bpg
        if data[:2] == b'\x36\x04':  # PSF1: UCS-2 LE, 0xFFFF ends a glyph, 0xFFFE starts sequences
            g = 0; seq = False
            while g < n and p + 1 < len(data):
                (u,) = struct.unpack('<H', data[p:p + 2]); p += 2
                if u == 0xFFFF: g += 1; seq = False
                elif u == 0xFFFE: seq = True
                elif not seq: cmap.setdefault(u, g)
        else:  # PSF2: UTF-8, 0xFF ends a glyph, 0xFE starts sequences
            for g in range(n):
                end = data.index(b'\xff', p); entry = data[p:end]; p = end + 1
                for s in entry.split(b'\xfe')[0:1]:
                    for ch in s.decode('utf-8', 'ignore'):
                        cmap.setdefault(ord(ch), g)
    else:
        cmap = {i: i for i in range(n)}
    def pixels(g):
        return [[(glyphs[g][y * row + x // 8] >> (7 - x % 8)) & 1 for x in range(w)] for y in range(h)]
    return w, h, cmap, pixels

def main():
    src, name, out = sys.argv[1:4]
    term = len(sys.argv) > 4 and sys.argv[4] == 'term'
    w, h, cmap, pixels = load_psf(src)
    # baseline: one row below the bottom of 'H'
    H = pixels(cmap[ord('H')])
    base = max(y for y in range(h) if any(H[y])) + 1
    descent = h - base
    codes = list(range(0x20, 0x7F)) + [c for c in (0xB0, 0xB7, 0x2022, 0x2026, 0x2190, 0x2191, 0x2192, 0x2193, 0x25B2, 0x25BC) if c in cmap]
    if term:
        more = [0xA0, 0xA9, 0xB1, 0xBB, 0xAB, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2122, 0x2261,
                0x2264, 0x2265, 0x2318, 0x23CE, 0x25A0, 0x25B6, 0x25C0, 0x25C6, 0x25CF, 0x2713, 0x2717]
        more += list(range(0x2500, 0x25A0))
        codes = sorted(set(codes[:0x7F - 0x20]) | {c for c in codes[0x7F - 0x20:]} | {c for c in more if c in cmap})
    bitmap, dsc, idx = [], [], 0
    for c in codes:
        px = pixels(cmap.get(c, cmap[ord('?')]))
        ys = [y for y in range(h) if any(px[y])]
        xs = [x for x in range(w) if any(px[y][x] for y in range(h))]
        if not ys:
            dsc.append((idx, w * 16, 0, 0, 0, 0)); continue
        y0, y1, x0, x1 = ys[0], ys[-1], xs[0], xs[-1]
        bits = [px[y][x] for y in range(y0, y1 + 1) for x in range(x0, x1 + 1)]
        bits += [0] * (-len(bits) % 8)
        by = [int(''.join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)]
        bw, bh = x1 - x0 + 1, y1 - y0 + 1
        dsc.append((idx, w * 16, bw, bh, x0, base - 1 - y1))  # ofs_y: box bottom above baseline
        bitmap.append((c, by)); idx += len(by)
    o = [f'/* {name}: generated by tools/psf2lvgl.py from {src.split("/")[-1]} ({w}x{h}, 1 bpp, exact pixels) */',
         '#include "lvgl.h"', '', 'static const uint8_t glyph_bitmap[] = {']
    for c, by in bitmap:
        o.append(f'    /* U+{c:04X} */ ' + ', '.join(f'0x{b:02x}' for b in by) + ',')
    o += ['    0x00', '};', '', 'static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {',
          '    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},']
    for d in dsc:
        o.append('    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d},' % d)
    o += ['};', '']
    extra = codes[0x7F - 0x20:]
    if extra:
        o.append('static const uint16_t unicode_list[] = {' + ', '.join(f'0x{c - extra[0]:x}' for c in extra) + '};')
    o += ['static const lv_font_fmt_txt_cmap_t cmaps[] = {',
          '    {.range_start = 32, .range_length = 95, .glyph_id_start = 1, .unicode_list = NULL,',
          '     .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},']
    if extra:
        o += [f'    {{.range_start = {extra[0]}, .range_length = {extra[-1] - extra[0] + 1}, .glyph_id_start = 96, .unicode_list = unicode_list,',
              f'     .glyph_id_ofs_list = NULL, .list_length = {len(extra)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},']
    o += ['};', '', 'static const lv_font_fmt_txt_dsc_t font_dsc = {',
          '    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL,',
          f'    .kern_scale = 0, .cmap_num = {2 if extra else 1}, .bpp = 1, .kern_classes = 0, .bitmap_format = 0,', '};', '',
          f'const lv_font_t {name} = {{',
          '    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,',
          f'    .line_height = {h}, .base_line = {descent}, .subpx = LV_FONT_SUBPX_NONE,',
          '    .underline_position = -1, .underline_thickness = 1, .dsc = &font_dsc,', '};', '']
    open(out, 'w').write('\n'.join(o))
    print(f'{name}: {w}x{h} baseline {base} descent {descent}, {len(codes)} glyphs')

main()
